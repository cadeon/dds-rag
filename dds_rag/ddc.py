def get_main_class(ddc_number: float) -> int:
    """Return the main 000-level class for a DDC number.
    E.g., 516.37 -> 500, 170 -> 100, 005 -> 0
    """
    return int(ddc_number // 100) * 100


def get_parent(ddc_number: float) -> float:
    """Return the parent class for a DDC number.
    E.g., 516.37 -> 510, 516.3 -> 510, 516 -> 500
    """
    # If it has decimals, truncate to 10-level
    if ddc_number % 10 != 0:
        return int(ddc_number // 10) * 10
    # If it's a 100-level, return the main class
    if ddc_number % 100 == 0:
        return ddc_number
    return int(ddc_number // 100) * 100


def get_siblings(ddc_number: float) -> list[float]:
    """Return sibling DDC numbers at the same level.
    E.g., 516.37 -> [516.35, 516.38, 516.39]
    """
    parent = get_parent(ddc_number)
    # Find all numbers with the same parent
    siblings = [n for n in DDC_CLASSES if get_parent(n) == parent and n != ddc_number]
    return sorted(siblings)


def get_label(ddc_number: float) -> str:
    """Return the human-readable label for a DDC number."""
    if ddc_number in DDC_CLASSES:
        return DDC_CLASSES[ddc_number]
    # Try main class
    main = get_main_class(ddc_number)
    if main in MAIN_CLASSES:
        return f"{int(ddc_number)} - {MAIN_CLASSES[main]}"
    return str(int(ddc_number))


def get_ddc_tree() -> dict:
    """Return DDC classes organized by main class for UI display."""
    tree: dict[int, list[tuple[float, str]]] = {}
    for main_cls in sorted(MAIN_CLASSES.keys()):
        tree[main_cls] = []
    for num, label in sorted(DDC_CLASSES.items()):
        main = get_main_class(num)
        if main in tree:
            tree[main].append((num, label))
    return tree
